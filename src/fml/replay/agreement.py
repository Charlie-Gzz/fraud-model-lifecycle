"""Does the full Kubernetes loop agree with the fast backtest on the same scenario and seed?

Compares, for each full-loop run in results/fullloop/: the days of drift alarms, retrains,
gate outcomes and promotions, and the fraud caught after drift. Expected gaps: in the
cluster a canary splits day d+1's traffic between versions, the drift check only uses
traffic served by the champion, and Evidently samples slightly different rows.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from fml import REPO_ROOT
from fml.backtest.runner import result_path
from fml.results import pooled

FULLLOOP = REPO_ROOT / "results" / "fullloop"


def _days(events: list[dict], kind: str) -> list[int]:
    return sorted({e["day"] for e in events if e["type"] == kind})


def compare(run_dir: Path) -> dict | None:
    summary = json.loads((run_dir / "summary.json").read_text())
    set_name, scenario = summary["scenario"].split("/")
    bt_path = result_path(set_name, scenario, "drift", summary["seed"])
    if not bt_path.exists() or summary["days_served"] < 60:
        return None
    bt = json.loads(bt_path.read_text())
    fl_events = [json.loads(x) for x in (run_dir / "timeline.jsonl").read_text().splitlines()]
    daily = json.loads((run_dir / "daily.json").read_text())
    start = summary["drift_start"] or 65
    end = max(d["day"] for d in daily)
    # The full loop's daily records do not carry dollars; compare fraud caught (recall).
    fl_post = pooled([{**d, "fraud_dollars": 0, "caught_dollars": 0} for d in daily], start, end)
    bt_post = pooled(bt["days"], start, end)
    out = {"run": run_dir.name, "scenario": summary["scenario"], "seed": summary["seed"]}
    for kind in (
        "drift_detected",
        "retrain_started",
        "gate_passed",
        "gate_failed",
        "promoted",
        "rolled_back",
    ):
        fl = [d for d in _days(fl_events, kind) if d > 35]
        bk = [d for d in _days(bt["events"], kind) if d > 35]
        out[kind] = {"full_loop": fl, "backtest": bk, "same": fl == bk}
    out["recall_after_drift"] = {
        "full_loop": fl_post,
        "backtest": bt_post,
        "gap_points": 100 * (fl_post - bt_post),
    }
    by_day = {d["day"]: d["recall"] for d in bt["days"]}
    diffs = [
        abs(d["recall"] - by_day[d["day"]])
        for d in daily
        if d["day"] in by_day and not np.isnan(d["recall"]) and not np.isnan(by_day[d["day"]])
    ]
    out["daily_recall_identical_share"] = (
        float(np.mean([x < 1e-9 for x in diffs])) if diffs else None
    )
    return out


def build() -> list[dict]:
    rows = [
        r
        for p in sorted(FULLLOOP.glob("*"))
        if (p / "summary.json").exists()
        for r in [compare(p)]
        if r
    ]
    (FULLLOOP / "agreement.json").write_text(json.dumps(rows, indent=1, default=float))
    lines = [
        "# Full loop vs fast backtest",
        "",
        "Same scenario, seed, data, features, windows, policy and seeds. Generated by "
        "`fml assets`.",
        "",
        "| Run | Retrain days (cluster) | Retrain days (backtest) | Promotions match | "
        "Fraud caught after drift: cluster vs backtest |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        rec = r["recall_after_drift"]
        lines.append(
            f"| {r['scenario']} seed {r['seed']} | {r['retrain_started']['full_loop']} | "
            f"{r['retrain_started']['backtest']} | {'yes' if r['promoted']['same'] else 'no'} | "
            f"{100 * rec['full_loop']:.1f}% vs {100 * rec['backtest']:.1f}% "
            f"({rec['gap_points']:+.1f} pts) |"
        )
    (FULLLOOP / "agreement.md").write_text("\n".join(lines) + "\n")
    return rows
