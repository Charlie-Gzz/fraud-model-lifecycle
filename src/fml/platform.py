"""Bring the local platform up and down: kind cluster, Helm releases, images, port-forwards.

Everything runs locally. Passwords are generated into .env (gitignored) and handed to
Terraform through TF_VAR_* environment variables, so they never appear on a command line.
"""

from __future__ import annotations

import json
import os
import secrets
import subprocess
import sys
import time

from fml import REPO_ROOT
from fml.tools import install_all, tool_env, tool_path

RUN_DIR = REPO_ROOT / ".run"
KUBECONFIG = RUN_DIR / "kubeconfig"
ENV_FILE = REPO_ROOT / ".env"
PF_FILE = RUN_DIR / "port-forwards.json"
CLUSTER = "fml"
LABEL = "project=fraud-model-lifecycle"

# name -> (build context, Dockerfile). Every image is built locally and loaded into kind.
IMAGES = {
    "fml-mlflow:0.1.0": ("images/mlflow", "images/mlflow/Dockerfile"),
    "fml-runtime:0.1.0": (".", "images/runtime/Dockerfile"),
    "fml-spark:0.1.0": (".", "images/spark/Dockerfile"),
}

# local port -> (namespace, service, service port). All bound to 127.0.0.1 only.
PORT_FORWARDS = {
    5000: ("fml", "mlflow", 5000),
    8333: ("fml", "seaweedfs", 8333),
    8000: ("fml", "fraud-scorer", 80),
    3000: ("monitoring", "kps-grafana", 80),
    9090: ("monitoring", "kps-kube-prometheus-stack-prometheus", 9090),
    9093: ("monitoring", "kps-kube-prometheus-stack-alertmanager", 9093),
    2746: ("argo", "argo-workflows-server", 2746),
    3100: ("argo-rollouts", "argo-rollouts-dashboard", 3100),
}

SECRET_KEYS = {
    "POSTGRES_PASSWORD": "postgres_password",
    "S3_ACCESS_KEY": "s3_access_key",
    "S3_SECRET_KEY": "s3_secret_key",
    "GRAFANA_ADMIN_PASSWORD": "grafana_admin_password",
}


def log(msg: str) -> None:
    print(f"[fml] {msg}", flush=True)


# --- secrets -----------------------------------------------------------------


def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        return {}
    pairs = (line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line)
    return {k.strip(): v.strip() for k, v in pairs if not k.startswith("#")}


def ensure_env() -> dict[str, str]:
    """Create .env with random local passwords on first run. Values are never printed."""
    env = read_env()
    missing = [k for k in SECRET_KEYS if k not in env]
    if missing:
        for key in missing:
            env[key] = secrets.token_urlsafe(24)
        body = "\n".join(f"{k}={env[k]}" for k in SECRET_KEYS)
        ENV_FILE.write_text(
            "# Local-only passwords generated by `fml up`. Never commit.\n" + body + "\n"
        )
        log(f"generated {len(missing)} local password(s) into .env")
    return env


# --- running tools -----------------------------------------------------------


def run(
    cmd: list[str], check: bool = True, quiet: bool = False, **kw
) -> subprocess.CompletedProcess:
    env = tool_env()
    env["KUBECONFIG"] = str(KUBECONFIG)
    env.update(kw.pop("env", {}))
    out = subprocess.PIPE if quiet else None
    proc = subprocess.run(
        cmd, cwd=kw.pop("cwd", REPO_ROOT), env=env, stdout=out, stderr=out, text=True, **kw
    )
    if check and proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or "")[-2000:] if quiet else ""
        raise RuntimeError(f"command failed ({proc.returncode}): {' '.join(cmd[:3])} ...\n{detail}")
    return proc


def kubectl(*args: str, **kw) -> subprocess.CompletedProcess:
    return run([str(tool_path("kubectl")), *args], **kw)


def terraform(stage: str, *args: str, tf_vars: dict[str, str] | None = None) -> None:
    env = {f"TF_VAR_{k}": v for k, v in (tf_vars or {}).items()}
    env["TF_IN_AUTOMATION"] = "1"
    cwd = REPO_ROOT / "infra" / stage
    tf = str(tool_path("terraform"))
    if not (cwd / ".terraform").exists():
        run([tf, "init", "-input=false", "-no-color"], cwd=cwd, env=env, quiet=True)
    run([tf, *args, "-input=false", "-no-color"], cwd=cwd, env=env)


def cluster_exists() -> bool:
    out = run([str(tool_path("kind")), "get", "clusters"], quiet=True, check=False).stdout or ""
    return CLUSTER in out.split()


# --- images ------------------------------------------------------------------


def build_images(only: list[str] | None = None) -> None:
    for tag, (context, dockerfile) in IMAGES.items():
        if only and not any(tag.startswith(o) for o in only):
            continue
        if not (REPO_ROOT / dockerfile).exists():
            log(f"skip {tag}: {dockerfile} not written yet")
            continue
        log(f"building {tag}")
        run(
            ["docker", "build", "-q", "--label", LABEL, "-t", tag, "-f", dockerfile, context],
            quiet=True,
        )
        log(f"loading {tag} into kind")
        run([str(tool_path("kind")), "load", "docker-image", tag, "--name", CLUSTER], quiet=True)


# --- port-forwards -----------------------------------------------------------


def _pid_alive(pid: int) -> bool:
    out = subprocess.run(
        ["tasklist", "/FI", f"PID eq {pid}", "/NH"], capture_output=True, text=True
    ).stdout
    return str(pid) in out


def start_port_forwards() -> None:
    stop_port_forwards()
    RUN_DIR.mkdir(exist_ok=True)
    flags = subprocess.CREATE_NEW_PROCESS_GROUP | subprocess.DETACHED_PROCESS
    pids = {}
    for port, (ns, svc, svc_port) in PORT_FORWARDS.items():
        logf = open(RUN_DIR / f"pf-{port}.log", "w")  # noqa: SIM115 - handed to the child
        cmd = [
            sys.executable,
            "-m",
            "fml.portforward",
            str(KUBECONFIG),
            ns,
            svc,
            str(port),
            str(svc_port),
        ]
        proc = subprocess.Popen(
            cmd, cwd=REPO_ROOT, env=tool_env(), stdout=logf, stderr=logf, creationflags=flags
        )
        pids[str(port)] = proc.pid
    PF_FILE.write_text(json.dumps(pids, indent=2))
    log("port-forwards on 127.0.0.1: " + ", ".join(str(p) for p in PORT_FORWARDS))


def stop_port_forwards() -> None:
    if not PF_FILE.exists():
        return
    for pid in json.loads(PF_FILE.read_text()).values():
        if _pid_alive(pid):
            subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"], capture_output=True)
    PF_FILE.unlink()


# --- smoke check -------------------------------------------------------------


def wait_ready(timeout_s: int = 900) -> None:
    for ns in ["fml", "monitoring", "argo", "argo-rollouts"]:
        log(f"waiting for deployments in {ns}")
        kubectl(
            "wait",
            "--for=condition=Available",
            "deployment",
            "--all",
            "-n",
            ns,
            f"--timeout={timeout_s}s",
            quiet=True,
        )
    kubectl(
        "rollout",
        "status",
        "statefulset/postgres",
        "-n",
        "fml",
        f"--timeout={timeout_s}s",
        quiet=True,
    )


def smoke_check(retries: int = 30) -> dict[str, bool]:
    """Every service answers on its forwarded localhost port."""
    import httpx

    checks = {
        "mlflow": "http://127.0.0.1:5000/health",
        "seaweedfs-s3": "http://127.0.0.1:8333/",
        "grafana": "http://127.0.0.1:3000/api/health",
        "prometheus": "http://127.0.0.1:9090/-/ready",
        "alertmanager": "http://127.0.0.1:9093/-/ready",
        "argo-workflows": "http://127.0.0.1:2746/api/v1/version",
        "argo-rollouts": "http://127.0.0.1:3100/rollouts/",
    }
    if kubectl("get", "svc", "fraud-scorer", "-n", "fml", check=False, quiet=True).returncode == 0:
        checks["fraud-scorer"] = "http://127.0.0.1:8000/healthz"
    result = {}
    for name, url in checks.items():
        ok = False
        for _ in range(retries):
            try:
                ok = httpx.get(url, timeout=5).status_code < 500
            except httpx.HTTPError:
                ok = False
            if ok:
                break
            time.sleep(2)
        result[name] = ok
    # Redis and Postgres are not HTTP: check them from inside their pods.
    result["redis"] = (
        "PONG"
        in kubectl(
            "exec", "-n", "fml", "deploy/redis", "--", "redis-cli", "ping", quiet=True, check=False
        ).stdout
    )
    result["postgres"] = (
        kubectl(
            "exec",
            "-n",
            "fml",
            "postgres-0",
            "--",
            "pg_isready",
            "-U",
            "mlflow",
            quiet=True,
            check=False,
        ).returncode
        == 0
    )
    return result


# --- top level ---------------------------------------------------------------


def up(skip_images: bool = False) -> dict[str, bool]:
    install_all()
    env = ensure_env()
    RUN_DIR.mkdir(exist_ok=True)
    if not cluster_exists():
        log("creating kind cluster (terraform: infra/cluster)")
        terraform(
            "cluster", "apply", "-auto-approve", tf_vars={"kubeconfig_path": KUBECONFIG.as_posix()}
        )
    else:
        run(
            [
                str(tool_path("kind")),
                "export",
                "kubeconfig",
                "--name",
                CLUSTER,
                "--kubeconfig",
                str(KUBECONFIG),
            ],
            quiet=True,
        )
    if not skip_images:
        build_images()
    log("installing platform (terraform: infra/platform)")
    tf_vars = {var: env[key] for key, var in SECRET_KEYS.items()}
    tf_vars["kubeconfig_path"] = KUBECONFIG.as_posix()
    terraform("platform", "apply", "-auto-approve", tf_vars=tf_vars)
    if (REPO_ROOT / "k8s" / "kustomization.yaml").exists():
        log("applying app manifests (k8s/)")
        kubectl("apply", "-k", "k8s", quiet=True)
    wait_ready()
    start_port_forwards()
    result = smoke_check()
    for name, ok in result.items():
        log(f"  {'ok ' if ok else 'FAIL'} {name}")
    return result


def down() -> None:
    stop_port_forwards()
    if not cluster_exists():
        log("no cluster running")
        return
    log("deleting the kind cluster (terraform destroy)")
    terraform(
        "cluster", "destroy", "-auto-approve", tf_vars={"kubeconfig_path": KUBECONFIG.as_posix()}
    )
    # The platform releases lived inside the cluster, so they are gone with it.
    # Drop the now-stale platform state so the next `fml up` starts clean.
    for f in (REPO_ROOT / "infra" / "platform").glob("terraform.tfstate*"):
        f.unlink()
    log("cluster removed; images kept for a fast restart")


def status() -> None:
    if not cluster_exists():
        log("cluster: not running")
        return
    kubectl("get", "pods", "-A", "-l", "!job-name", "--sort-by=.metadata.namespace")
    pf = json.loads(PF_FILE.read_text()) if PF_FILE.exists() else {}
    alive = [p for p, pid in pf.items() if _pid_alive(pid)]
    log(f"port-forwards alive: {', '.join(alive) or 'none'}")
    mem = subprocess.run(
        ["docker", "stats", "--no-stream", "--format", "{{.MemUsage}}", f"{CLUSTER}-control-plane"],
        capture_output=True,
        text=True,
    ).stdout
    log(f"cluster memory (docker stats): {mem.strip()}")


def env_for_python() -> dict[str, str]:
    """Env vars for host-side Python that talks to the forwarded services."""
    env = read_env()
    return {
        "MLFLOW_TRACKING_URI": "http://127.0.0.1:5000",
        "MLFLOW_S3_ENDPOINT_URL": "http://127.0.0.1:8333",
        "AWS_ACCESS_KEY_ID": env.get("S3_ACCESS_KEY", ""),
        "AWS_SECRET_ACCESS_KEY": env.get("S3_SECRET_KEY", ""),
        "AWS_DEFAULT_REGION": "us-east-1",
        "KUBECONFIG": str(KUBECONFIG),
        "PATH": os.environ.get("PATH", ""),
    }
